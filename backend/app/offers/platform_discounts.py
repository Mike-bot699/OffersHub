"""Discount codes and sales by discount from the Eli Z platform API.

Declared choices:
- Codes are grouped by campaign when a campaign holds five or more codes: these are single-use
  codes generated by automations (e.g. 2QKRFMRP under THANKS20), stored as one discount named
  after the campaign. A campaign with fewer codes keeps each code (a code and its title can differ).
- Sales rows of grouped codes take the campaign's name, so offers, the Discount codes list and the
  technical status all match on the same name.
- The code list holds codes only: automatic discounts are not in it (they are in the sales rows),
  so a missing automatic discount is never read as "does not exist".
- Days are the store's own business days, used as given.
"""

from collections import defaultdict
from datetime import date, datetime, timedelta

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from app.db.base import utcnow
from app.models import Coupon, DiscountReport, DiscountReportRow, Store
from app.offers.discount_report import map_rows, parse_rows, replace_platform_report

SOURCE = "elizeta"
GROUP_MIN = 5
REFRESH_DAYS = 7      # an incremental sync re-reads the last week (late orders, refunds)
FULL_EVERY_DAYS = 7   # and the whole window is re-read weekly
HISTORY_SLACK_DAYS = 31
VALUE_TYPES = {"percentage": "percent", "percent": "percent", "fixed_amount": "fixed", "fixed": "fixed",
               "free_shipping": "free_shipping", "shipping": "free_shipping"}


def _dt(v) -> datetime | None:
    if not v:
        return None
    try:
        return datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    except ValueError:
        return None


def _int(v) -> int | None:
    try:
        return int(float(v)) if v not in (None, "") else None
    except (TypeError, ValueError):
        return None


def _float(v) -> float | None:
    try:
        return float(v) if v not in (None, "") else None
    except (TypeError, ValueError):
        return None


def campaign_map(rows: list[dict]) -> dict[str, str]:
    """Upper-case code -> campaign, for codes of campaigns with GROUP_MIN or more codes."""
    by_campaign: dict[str, list[str]] = defaultdict(list)
    for r in rows:
        code = str(r.get("code") or "").strip().upper()
        camp = str(r.get("campaign") or "").strip().upper()
        if code and camp:
            by_campaign[camp].append(code)
    return {c: camp for camp, codes in by_campaign.items() if len(set(codes)) >= GROUP_MIN for c in codes}


def store_codes(db: Session, store: Store, rows: list[dict], *, complete: bool) -> dict:
    """Replace the store's platform code list (rows with snake_case keys)."""
    groups = campaign_map(rows)
    merged: dict[str, dict] = {}
    for r in rows:
        code = str(r.get("code") or "").strip().upper()
        if not code:
            continue
        key = groups.get(code, code)[:128]
        status = (str(r.get("status") or "").strip().lower() or None)
        m = merged.setdefault(key, {"codes": 0, "statuses": set(), "usage": 0, "rows": []})
        m["codes"] += 1
        m["statuses"].add(status)
        m["usage"] += _int(r.get("usage_count")) or 0
        m["rows"].append(r)
    now = utcnow()
    existing = {c.code: c for c in db.scalars(select(Coupon).where(Coupon.store_id == store.id, Coupon.source == SOURCE))}
    for key, m in merged.items():
        # A group is as alive as its liveliest code; its dates and value come from its newest code.
        st = next((s for s in ("active", "scheduled", "expired") if s in m["statuses"]), next(iter(m["statuses"])))
        r = max(m["rows"], key=lambda x: str(x.get("starts_at") or ""))
        c = existing.pop(key, None) or Coupon(store_id=store.id, code=key, source=SOURCE)
        if c.id is None:
            db.add(c)
        title = str(r.get("title") or key)[:300] if m["codes"] == 1 else f"{key} ({m['codes']} single-use codes)"
        vt = str(r.get("value_type") or "").lower()
        c.title, c.status, c.usage_count = title, st, m["usage"]
        c.value_type, c.value = VALUE_TYPES.get(vt), abs(_float(r.get("value")) or 0) or None
        c.usage_limit = _int(r.get("usage_limit")) if m["codes"] == 1 else None
        c.starts_at, c.ends_at = _dt(r.get("starts_at")), _dt(r.get("ends_at"))
        c.channel, c.last_synced_at = "code", now
        c.raw = {"campaign": r.get("campaign"), "codes": m["codes"]}
    removed = 0
    if complete:  # only a complete list proves a code is gone
        for c in existing.values():
            db.delete(c)
            removed += 1
    store.constraints = {**(store.constraints or {}), "discount_codes_api": {
        "complete": complete, "imported_at": now.isoformat(), "rows": len(rows)}}
    db.flush()
    return {"codes": len(rows), "discounts": len(merged), "grouped_campaigns": len(set(groups.values())),
            "removed": removed, "complete": complete}


def platform_report(db: Session, store: Store) -> DiscountReport | None:
    return db.scalar(select(DiscountReport).where(DiscountReport.store_id == store.id, DiscountReport.source == SOURCE))


def read_from(db: Session, store: Store, window_start: date, today: date) -> date | None:
    """First day to read, or None for the whole window: no report yet, a weekly full read due, or a
    history that does not reach back to the window yet (the platform was still loading it)."""
    rep = platform_report(db, store)
    if rep is None or not rep.by_day or rep.period_start > window_start + timedelta(days=HISTORY_SLACK_DAYS):
        return None
    made = rep.created_at.date() if rep.created_at else None
    if made is None or (today - made).days >= FULL_EVERY_DAYS:
        return None
    return max(rep.period_end - timedelta(days=REFRESH_DAYS), window_start)


def store_sales(db: Session, store: Store, rows: list[dict], start: date, end: date, groups: dict[str, str],
                *, since: date | None = None) -> dict:
    """Sales by discount and day into the store's rolling platform report. With `since`, only the
    days from `since` are replaced and the earlier ones kept."""
    mapped = map_rows(rows)
    for r in mapped:
        r["name"] = groups.get(str(r["name"]).strip().upper(), r["name"])
    parsed = parse_rows(mapped)
    days = sorted({p["day"] for p in parsed if p["day"]})
    rep = platform_report(db, store)
    if since and rep is not None:
        db.execute(delete(DiscountReportRow).where(DiscountReportRow.report_id == rep.id, DiscountReportRow.day >= since))
        db.add_all([DiscountReportRow(report_id=rep.id, store_id=store.id, **p) for p in parsed])
        if days:
            rep.period_end = max(rep.period_end, days[-1])
        db.flush()
        return {"mode": "incremental", "since": since.isoformat(), "rows": len(parsed), "days": len(days),
                "first_day": rep.period_start.isoformat(), "last_day": rep.period_end.isoformat(), "by_day": rep.by_day,
                "orders": sum(p["orders"] for p in parsed)}
    if not parsed:
        return {"mode": "full", "rows": 0}
    # The period is the days actually present: a history still loading must not look like zero sales.
    first, last = (days[0], days[-1]) if days else (start, end)
    report = replace_platform_report(db, store, parsed, first, last)
    return {"mode": "full", "rows": len(parsed), "first_day": first.isoformat(), "last_day": last.isoformat(), "days": len(days),
            "by_day": report.by_day, "orders": sum(p["orders"] for p in parsed)}
